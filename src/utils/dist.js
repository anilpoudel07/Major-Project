function snapToRoute(lat, lon, route) {
  let minDist = Infinity;
  let closestPoint = route[0];

  for (const point of route) {
    const d = haversine(lat, lon, point.lat, point.lon);
    if (d < minDist) {
      minDist = d;
      closestPoint = point;
    }
  }

  return closestPoint;
}


export function calculateDistance(
  startLat,
  startLon,
  currentLat,
  currentLon,
  route
) {
  const startPoint = snapToRoute(startLat, startLon, route);
  const currentPoint = snapToRoute(currentLat, currentLon, route);
  console.log("start poit: ", startPoint);
  console.log("current: ",currentPoint);
  
  

  return Math.abs(currentPoint.km - startPoint.km);
}
